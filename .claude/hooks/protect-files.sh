#!/bin/bash
# PreToolUse(Edit|Write|MultiEdit): some files must never be edited by hand.
# Exit 2 blocks the edit and tells Claude what to do instead.

file=$(jq -r '.tool_input.file_path // empty')

case "$file" in
    */GeneratedStringSymbols_*.swift)
        echo "Blocked: $file is generated by xcstringstool. Edit the package's Localizable.xcstrings instead (use the localize skill); symbols are regenerated automatically." >&2
        exit 2 ;;
    */Secrets.xcconfig | */GeneratedSecrets.swift)
        echo "Blocked: $file holds secrets and is managed by hand (Secrets.xcconfig is turned into GeneratedSecrets.swift at build time). Ask Martín to change it." >&2
        exit 2 ;;
esac
exit 0
